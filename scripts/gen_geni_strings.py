def collect(strings_file):
    """Returns the generated <string> elements of one upstream strings.xml (multi-line ones included)."""
    lines = []
    content = strings_file.read_text(encoding="utf-8")
    for m in STRING.finditer(content):
        if OLD in m.group(3) and m.group(2) != "app_name":
            text = m.group(3).replace(OLD, NEW)
            if re.search(r"family\s*gem", text, re.I):
                print(f"WARNING {strings_file.parent.name}/{m.group(2)}: still mentions Family Gem: {text}")
            lines.append(f"    {m.group(1)}{text}{m.group(4)}")
    # The Diagram view is named Tree
    tree = re.search(r'<string name="tree">(.*?)</string>', content, re.S)
    if tree:
        lines.append(f'    <string name="diagram">{tree.group(1)}</string>')
    if strings_file.parent.name in TREE_VIEW:
        settings, generations = TREE_VIEW[strings_file.parent.name]
        lines.append(f'    <string name="diagram_settings">{settings}</string>')
        lines.append(f'    <string name="generations_display_diagram">{generations}</string>')
    return lines


def expected():
    """Maps overlay path -> full expected content (for locales) or generated block (for values/)."""
    result = {}
    for f in sorted(UPSTREAM.glob("values*/strings.xml")):
        lines = collect(f)
        # The default file is always kept: its generated block is just emptied when nothing matches
        if lines or f.parent.name == "values":
            result[OVERLAY / f.parent.name / "strings.xml"] = lines
    return result


def render(path, lines):
    if path.parent.name == "values":
        current = path.read_text(encoding="utf-8")
        if BEGIN not in current or END not in current:
            sys.exit(f"{path.relative_to(ROOT)}: missing the {BEGIN} / {END} markers")
        block = BEGIN + "\n" + "".join(line + "\n" for line in lines) + "    " + END
        return re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, current, flags=re.S)
    return HEADER + "\n".join(lines) + "\n</resources>\n"


def main():
    check = "--check" in sys.argv
    stale = []
    wanted = expected()
    for path, lines in wanted.items():
        content = render(path, lines)
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    # Generated locale files whose source no longer mentions Family Gem
    for f in OVERLAY.glob("values-*/strings.xml"):
        if f not in wanted:
            stale.append(f)
            if not check:
                f.unlink()
    for path in stale:
        print(("STALE " if check else "wrote ") + str(path.relative_to(ROOT)))
    sys.exit(1 if check and stale else 0)


if __name__ == "__main__":
    main()
