#!/usr/bin/env python3
"""Generates the Treekin string overrides in app/src/geni/res from the upstream translations.

Every <string> of app/src/main/res/values*/strings.xml that contains "Family Gem"
(except app_name, which is overridden by hand) is copied with "Family Gem" replaced by "Treekin".
Upstream files are only read. Raw XML text is copied, so escapes and placeholders stay intact.

The graphical "Diagram" view is called "Tree" in Treekin: "diagram" takes the locale's own upstream "tree" word,
and the display settings strings come from TREE_VIEW below (resource IDs stay the same).

Usage: gen_geni_strings.py          rewrite the overlay files
       gen_geni_strings.py --check  write nothing, exit 1 if the overlay is stale
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UPSTREAM = ROOT / "app/src/main/res"
OVERLAY = ROOT / "app/src/geni/res"
OLD, NEW = "Family Gem", "Treekin"
BEGIN, END = "<!-- GENERATED:BEGIN -->", "<!-- GENERATED:END -->"
STRING = re.compile(r'(<string name="([^"]+)"[^>]*>)(.*?)(</string>)', re.S)
HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
          '    <!-- Generated by scripts/gen_geni_strings.py from the upstream translations: do not edit by hand -->\n')


